"""
Numerical Divergence & Multi-Precision Validation Suite.
Measures drift across FP32, BF16, and FP8 precision formats against PyTorch eager ground-truth.
"""

from dataclasses import dataclass
from enum import Enum
import math
from typing import Dict, List, Optional, Tuple
import numpy as np
import torch
from tabulate import tabulate
from rich.console import Console
from rich.table import Table

class PrecisionFormat(str, Enum):
    FP32 = "FP32"
    BF16 = "BF16"
    FP8_E4M3 = "FP8_E4M3"
    FP8_E5M2 = "FP8_E5M2"

@dataclass
class NumericalMetrics:
    precision: PrecisionFormat
    max_absolute_diff: float
    relative_error: float
    rmse: float
    cosine_similarity: float
    passed: bool
    status_message: str

# Defined in Section 4 of ARCHITECTURE_SPEC.md
TOLERANCE_THRESHOLDS = {
    PrecisionFormat.FP32: {"max_diff": 1e-4, "max_rel": 1e-4, "min_cosine": 0.999999},
    PrecisionFormat.BF16: {"max_diff": 5e-2, "max_rel": 2e-2, "min_cosine": 0.9995},
    PrecisionFormat.FP8_E4M3: {"max_diff": 1.5e-1, "max_rel": 5e-2, "min_cosine": 0.995},
    PrecisionFormat.FP8_E5M2: {"max_diff": 3.0e-1, "max_rel": 8e-2, "min_cosine": 0.990},
}

def compute_numerical_divergence(
    y_test: torch.Tensor,
    y_ref: torch.Tensor,
    precision: PrecisionFormat = PrecisionFormat.FP32,
) -> NumericalMetrics:
    """
    Computes numerical divergence metrics between test tensor and reference tensor.

    Args:
        y_test: Tensor generated by compiled pipeline or target precision.
        y_ref: Ground truth tensor from reference PyTorch eager execution (FP32).
        precision: PrecisionFormat being evaluated.

    Returns:
        NumericalMetrics: Computed difference metrics and pass/fail verdict.
    """
    test_flat = y_test.detach().to(torch.float32).flatten()
    ref_flat = y_ref.detach().to(torch.float32).flatten()

    diff = test_flat - ref_flat
    abs_diff = torch.abs(diff)

    # 1. Max Absolute Difference
    max_abs_diff = float(torch.max(abs_diff).item())

    # 2. Relative Error
    ref_norm = float(torch.norm(ref_flat, p=2).item())
    diff_norm = float(torch.norm(diff, p=2).item())
    rel_error = diff_norm / (ref_norm + 1e-12)

    # 3. Root Mean Square Error (RMSE)
    rmse = float(torch.sqrt(torch.mean(diff ** 2)).item())

    # 4. Cosine Similarity
    test_norm = float(torch.norm(test_flat, p=2).item())
    dot_product = float(torch.dot(test_flat, ref_flat).item())
    cosine_sim = dot_product / ((test_norm * ref_norm) + 1e-12)

    # Check tolerances
    thresholds = TOLERANCE_THRESHOLDS.get(
        precision,
        {"max_diff": 1e-2, "max_rel": 2e-2, "min_cosine": 0.999},
    )
    passed = (
        (max_abs_diff <= thresholds["max_diff"] or rel_error <= thresholds["max_rel"])
        and cosine_sim >= thresholds["min_cosine"]
    )

    status = "PASSED" if passed else "FAILED (Exceeds Tolerance)"
    return NumericalMetrics(
        precision=precision,
        max_absolute_diff=max_abs_diff,
        relative_error=rel_error,
        rmse=rmse,
        cosine_similarity=cosine_sim,
        passed=passed,
        status_message=status,
    )


def simulate_quantization(tensor: torch.Tensor, precision: PrecisionFormat) -> torch.Tensor:
    """Simulates target precision truncation / quantization."""
    t = tensor.detach().clone()
    if precision == PrecisionFormat.FP32:
        return t.to(torch.float32)
    elif precision == PrecisionFormat.BF16:
        return t.to(torch.bfloat16).to(torch.float32)
    elif precision == PrecisionFormat.FP8_E4M3:
        if hasattr(torch, "float8_e4m3fn"):
            return t.to(torch.float8_e4m3fn).to(torch.float32)
        # Software emulation: quantize to 8-bit dynamic range
        scale = torch.max(torch.abs(t)) / 240.0
        q = torch.clamp(torch.round(t / (scale + 1e-8)), -240.0, 240.0)
        return q * scale
    elif precision == PrecisionFormat.FP8_E5M2:
        if hasattr(torch, "float8_e5m2"):
            return t.to(torch.float8_e5m2).to(torch.float32)
        scale = torch.max(torch.abs(t)) / 57344.0
        q = torch.clamp(torch.round(t / (scale + 1e-8)), -57344.0, 57344.0)
        return q * scale
    return t


def verify_precision_suite(
    output_ref: torch.Tensor,
    custom_outputs: Optional[Dict[PrecisionFormat, torch.Tensor]] = None,
) -> List[NumericalMetrics]:
    """
    Evaluates drift across all precision formats (FP32, BF16, FP8_E4M3, FP8_E5M2).
    """
    results = []
    formats = [
        PrecisionFormat.FP32,
        PrecisionFormat.BF16,
        PrecisionFormat.FP8_E4M3,
        PrecisionFormat.FP8_E5M2,
    ]

    for fmt in formats:
        if custom_outputs and fmt in custom_outputs:
            test_tensor = custom_outputs[fmt]
        else:
            test_tensor = simulate_quantization(output_ref, fmt)

        metrics = compute_numerical_divergence(test_tensor, output_ref, fmt)
        results.append(metrics)

    return results


def format_divergence_table(metrics_list: List[NumericalMetrics]) -> str:
    """Formats divergence metrics into a markdown / tabulate table."""
    headers = [
        "Precision",
        "Max |Δ|",
        "Relative Error",
        "RMSE",
        "Cosine Similarity",
        "Status",
    ]
    rows = []
    for m in metrics_list:
        rows.append([
            m.precision.value,
            f"{m.max_absolute_diff:.2e}",
            f"{m.relative_error:.2e}",
            f"{m.rmse:.2e}",
            f"{m.cosine_similarity:.6f}",
            "✅ PASS" if m.passed else "❌ FAIL",
        ])
    return tabulate(rows, headers=headers, tablefmt="github")


def print_rich_divergence_table(metrics_list: List[NumericalMetrics]) -> None:
    """Displays styled terminal output using Rich."""
    console = Console()
    table = Table(
        title="MLIR-TensorOpt: Multi-Precision Drift Verification",
        header_style="bold cyan",
    )
    table.add_column("Precision", justify="center")
    table.add_column("Max |Δ|", justify="right")
    table.add_column("Rel Error", justify="right")
    table.add_column("RMSE", justify="right")
    table.add_column("Cosine Sim", justify="right")
    table.add_column("Verdict", justify="center")

    for m in metrics_list:
        status_style = "green bold" if m.passed else "red bold"
        verdict = "[green]✔ PASS[/green]" if m.passed else "[red]✘ FAIL[/red]"
        table.add_row(
            m.precision.value,
            f"{m.max_absolute_diff:.3e}",
            f"{m.relative_error:.3e}",
            f"{m.rmse:.3e}",
            f"{m.cosine_similarity:.6f}",
            verdict,
        )
    console.print(table)
